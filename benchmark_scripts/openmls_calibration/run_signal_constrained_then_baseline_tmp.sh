#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_ROOT"

# 1. Constrained Signal RAM sweep first, then CPU sweep.
SIGNAL_RAM_SWEEP_VALUES="10k,50k,100k,500k,1m,5m,10m,50m,100m,500m" \
PROTOCOL=signal SWEEP=both N=1 OUTPUT_ROOT=/dev/shm \
  SIGNAL_WORKERS=1024 SIGNAL_MIN_CONVERSATION_SIZE=10 SIGNAL_MAX_CONVERSATION_SIZE=1024 \
  SIGNAL_STEP_SIZE=32 STEP_SIZE_SWITCH_AT=256 STEP_SIZE_AFTER_SWITCH=128 \
  PLATEAU_ORDER=ascending PROFILED_SINGLETON_COUNT=10 SINGLETON_MIN_COUNT=10 \
  SIGNAL_APP_ROUNDS=1 SIGNAL_ROUNDTRIPS=1 MAX_APP_SAMPLES_PER_PAYLOAD=1 \
  PAYLOAD_SIZES=512 BUILD_IMAGES=1 RESOURCE_OUTPUT_VALIDATION=1 \
  bash "$SCRIPT_DIR/run_01_constrained_container_sweeps.sh"

# 2. Unconstrained Signal baseline with three message workflows per plateau.
PROTOCOL=signal OUTPUT_ROOT=/dev/shm WORKERS=1024 MIN_SIZE=10 MAX_SIZE=1024 \
  STEP_SIZE=32 STEP_SIZE_SWITCH_AT=256 STEP_SIZE_AFTER_SWITCH=128 \
  PLATEAU_ORDER=ascending ROUNDTRIPS=1 APP_ROUNDS=3 UPDATE_ROUNDS=0 \
  MAX_APP_SAMPLES_PER_PAYLOAD=3 MAX_UPDATE_SAMPLES_PER_PLATEAU=0 \
  PAYLOAD_SIZES=512 PROFILED_SINGLETON_COUNT=10 SINGLETON_MIN_COUNT=10 \
  SINGLETON_SELECTION_STRATEGY=evenly-spaced PACKED_PER_CONTAINER=64 \
  PACKED_INTERNAL_PARALLELISM=16 BUILD_IMAGES=0 MIN_TMP_FREE_GB=10 \
  bash "$SCRIPT_DIR/run_02_tmp_exact_two_openmls_signal.sh"
