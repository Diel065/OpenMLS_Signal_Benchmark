#!/usr/bin/env bash
# Temporary constrained OpenMLS+Signal launcher using run_01_constrained_container_sweeps.sh.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

export OUTPUT_ROOT="${OUTPUT_ROOT:-/tmp}"
if [ "$OUTPUT_ROOT" != "/tmp" ]; then
  echo "ERROR: this temporary script is pinned to OUTPUT_ROOT=/tmp; got $OUTPUT_ROOT" >&2
  exit 2
fi

export PROTOCOL="${PROTOCOL:-both}"
export SWEEP="${SWEEP:-both}"
export N="${N:-1}"
export BUILD_IMAGES="${BUILD_IMAGES:-1}"

export WORKERS="${WORKERS:-2048}"
export MAX_GROUP_SIZE="${MAX_GROUP_SIZE:-2048}"
export PROFILED_SINGLETON_COUNT="${PROFILED_SINGLETON_COUNT:-10}"
export SINGLETON_MIN_COUNT="${SINGLETON_MIN_COUNT:-10}"
export SINGLETON_FRACTION="${SINGLETON_FRACTION:-0.000000001}"
export PACKED_PER_CONTAINER="${PACKED_PER_CONTAINER:-256}"
export PACKED_INTERNAL_PARALLELISM="${PACKED_INTERNAL_PARALLELISM:-16}"
export BRIDGE_COUNT="${BRIDGE_COUNT:-2}"
export STEP_SIZE="${STEP_SIZE:-16}"
export APP_ROUNDS="${APP_ROUNDS:-4}"
export UPDATE_ROUNDS="${UPDATE_ROUNDS:-4}"
export ROUNDTRIPS="${ROUNDTRIPS:-1}"
export MAX_APP_SAMPLES_PER_PAYLOAD="${MAX_APP_SAMPLES_PER_PAYLOAD:-4}"
export MAX_UPDATE_SAMPLES_PER_PLATEAU="${MAX_UPDATE_SAMPLES_PER_PLATEAU:-4}"
export PAYLOAD_SIZES="${PAYLOAD_SIZES:-32,512,2048}"

export SIGNAL_WORKERS="${SIGNAL_WORKERS:-512}"
export SIGNAL_MAX_CONVERSATION_SIZE="${SIGNAL_MAX_CONVERSATION_SIZE:-512}"
export SIGNAL_STEP_SIZE="${SIGNAL_STEP_SIZE:-8}"
export SIGNAL_APP_ROUNDS="${SIGNAL_APP_ROUNDS:-4}"
export SIGNAL_ROUNDTRIPS="${SIGNAL_ROUNDTRIPS:-1}"
export SIGNAL_PACKED_PER_CONTAINER="${SIGNAL_PACKED_PER_CONTAINER:-64}"
export SIGNAL_RAM_SWEEP_VALUES="${SIGNAL_RAM_SWEEP_VALUES:-8m,16m,32m,64m,128m,256m,512m,1g,2g,3g}"

exec "$SCRIPT_DIR/run_01_constrained_container_sweeps.sh"
